"""Generate ``fast_f32_variants.h``: CUTLASS's warp-level 3xTF32 MMA with other split rounding and product counts.

CUTLASS's ``MmaTensorOpFastF32`` (``cutlass/gemm/warp/mma_tensor_op_fast_f32.h``) fixes its split as big =
round-toward-zero, small = round-half-ulp-truncate, three products. Its own ``FastF32`` traits already support
round-to-nearest and a fourth (small * small) product, but the class hard-codes them. This script copies the
class body under two new names with other traits and adds warp-level defaults for two new operator tags, so the
threadblock and device templates pick them like ``arch::OpMultiplyAddFastF32``:

- ``OpMultiplyAddFastF32Rn3``: big and small round to nearest, three products (Ootomo and Yokota's split);
- ``OpMultiplyAddFastF32Rn4``: the same plus small * small.

Used by ``build.sh`` against a pinned CUTLASS checkout (v4.8.1); the header is generated, not vendored.
    python gen_variants.py CUTLASS_INCLUDE OUT_HEADER
"""

import re
import sys
from pathlib import Path

VARIANTS = {"Rn3": "k3xTF32", "Rn4": "k4xTF32"}


def class_body(source: str) -> str:
    start = source.index("/// Structure to compute the matrix product targeting CUDA cores and SIMT math instructions.")
    end = source.rindex("} // namespace warp")
    return source[start:end]


def main(include: str, out: str) -> None:
    source = (Path(include) / "cutlass/gemm/warp/mma_tensor_op_fast_f32.h").read_text()
    body = class_body(source)
    traits = re.compile(r"using MmaFastF32 = FastF32 <.*?>;", re.S)
    if len(traits.findall(body)) != 1:
        raise SystemExit("unexpected CUTLASS header: MmaFastF32 traits not found once")
    parts = ["// Generated by tools/bench/tc_gemm/gen_variants.py from CUTLASS's mma_tensor_op_fast_f32.h; do not edit.",
             "#pragma once", '#include "cutlass/gemm/warp/mma_tensor_op_fast_f32.h"',
             '#include "cutlass/gemm/warp/default_mma_tensor_op_sm80.h"',
             "namespace cutlass { namespace arch {"]
    parts += [f"struct OpMultiplyAddFastF32{v} {{}};" for v in VARIANTS]
    parts.append("} }  // namespace cutlass::arch\nnamespace cutlass { namespace gemm { namespace warp {")
    for name, count in VARIANTS.items():
        cls = body.replace("MmaTensorOpFastF32", f"MmaTensorOpFastF32{name}")
        cls = traits.sub("using MmaFastF32 = FastF32<FloatRoundStyle::round_to_nearest, FloatRoundStyle::round_to_nearest, "
                         "FloatRoundStyle::round_to_nearest, FloatRoundStyle::round_to_nearest, "
                         f"TensorFloat32Op::{count}>;", cls)
        parts.append(cls)
        parts.append(f"""
template <typename WarpShape_, typename InstructionShape_, typename LayoutA, typename LayoutB, typename LayoutC,
          int PartitionsK, bool AccumulatorsInRowMajor>
struct DefaultMmaTensorOp<WarpShape_, InstructionShape_, float, LayoutA, float, LayoutB, float, LayoutC,
                          arch::OpMultiplyAddFastF32{name}, PartitionsK, AccumulatorsInRowMajor> {{
  using Policy = cutlass::gemm::warp::MmaTensorOpPolicy<
      cutlass::arch::Mma<InstructionShape_, 32, cutlass::tfloat32_t, cutlass::layout::RowMajor, cutlass::tfloat32_t,
                         cutlass::layout::ColumnMajor, float, cutlass::layout::RowMajor, arch::OpMultiplyAdd>,
      cutlass::MatrixShape<1, 1> >;
  using Type = MmaTensorOpFastF32{name}<WarpShape_, float, LayoutA, float, LayoutB, float, LayoutC, Policy,
                                         PartitionsK, AccumulatorsInRowMajor>;
}};
""")
    parts.append("} } }  // namespace cutlass::gemm::warp\n")
    Path(out).write_text("\n".join(parts))


if __name__ == "__main__":
    main(*sys.argv[1:])
