CONFIGS = [(1, 160), (2, 160), (3, 160), (2, 80), (3, 80), (2, 40)]


def main():
    fns = "".join(wgmma_fn(n) for n in sorted({n for _, n in CONFIGS}))
    runs = "".join(RUN.replace("__WGS__", str(w)).replace("__NI__", str(n)) for w, n in CONFIGS)
    src = SOURCE.replace("__NR__", str(NR)).replace("__WGMMA__", fns).replace("__RUNS__", runs)
    # the kernel template calls wgmma_n<NI>: dispatch through a constexpr if
    disp = "".join(f"    if constexpr (NI == {n}) wgmma_n{n}(d, a, desc, scale);\n" for n in sorted({n for _, n in CONFIGS}))
    src = src.replace("wgmma_n__NI__(", "wgmma_ni<NI>(")
    src = src.replace("__device__ __forceinline__ uint64_t gmma_desc",
                      "template <int NI>\n__device__ __forceinline__ void wgmma_ni(float* d, const unsigned (&a)[4], "
                      "uint64_t desc, int scale) {\n" + disp + "}\n__device__ __forceinline__ uint64_t gmma_desc", 1)
    print(src)


if __name__ == "__main__":
    main()
